/** 单个字符的宽度（含 1 像素间隔）。 */
export const GLYPH_WIDTH = 3
/** 单个字符的高度。 */
export const GLYPH_HEIGHT = 5
/** 字符前进步进。 */
export const ADVANCE = 4

/**
 * 计算一段文本的像素宽度。
 * @param text - 文本内容。
 * @returns 宽度（像素）。
 */
export function measureText(text) {
  if (text.length === 0) return 0
  return text.length * ADVANCE - 1
}

/**
 * 绘制一段文本。
 * @param fb - 像素缓冲。
 * @param text - 文本内容，小写自动转大写。
 * @param x - 左端横坐标。
 * @param y - 顶端纵坐标。
 * @param color - 文字颜色。
 * @param centered - 为 true 时以 x 为中心绘制。
 */
export function drawText(fb, text, x, y, color, centered = false) {
  const upper = text.toUpperCase()
  const originX = centered ? Math.round(x - measureText(upper) / 2) : Math.round(x)
  const originY = Math.round(y)
  for (let index = 0; index < upper.length; index += 1) {
    const glyph = GLYPHS[upper[index]]
    if (glyph === undefined) continue
    const origin = originX + index * ADVANCE
    for (let row = 0; row < GLYPH_HEIGHT; row += 1) {
      for (let column = 0; column < GLYPH_WIDTH; column += 1) {
        if (glyph[row][column] !== '#') continue
        fb.fillRect(origin + column, originY + row, 1, 1, color)
      }
    }
  }
}

/**
 * 绘制带描边的文本，保证在任何背景上可读。
 * @param fb - 像素缓冲。
 * @param text - 文本内容。
 * @param x - 左端横坐标。
 * @param y - 顶端纵坐标。
 * @param color - 文字颜色。
 * @param shadow - 描边颜色。
 * @param centered - 为 true 时以 x 为中心绘制。
 */
export function drawTextShadowed(fb, text, x, y, color, shadow = '#000000', centered = false) {
  drawText(fb, text, x + 1, y + 1, shadow, centered)
  drawText(fb, text, x, y, color, centered)
}
